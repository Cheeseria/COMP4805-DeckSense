# layer2c.py
import json
import ollama

FACT_CHECK_SYSTEM_PROMPT = """
You are a strict Magic: The Gathering Rules Judge and Fact Checker.
You are reviewing proposed combos and loops generated by a previous AI.
Your job is to verify if the proposed loops physically work according to the exact Oracle text and Mana Value of the cards cited.

CRITICAL ARITHMETIC RULES:
1. Calculate the exact mana cost of the loop based on the cards' Mana Value (cmc) and Oracle text (e.g., Buyback costs).
2. Calculate the exact mana generated by the loop.
3. If Total Mana Generated < Total Mana Required, you MUST REJECT the loop.
4. If the loop requires a cost reducer (like Vadrik or Goblin Electromancer) to function, and that reducer is NOT listed in the loop's cards or required_assumptions, you MUST REJECT the loop. 

Output JSON ONLY in this format:
{
  "validated_loops": [
    {
      "original_cycle": ["Card A", "Card B"],
      "is_valid": true,
      "reasoning": "Card A produces X mana, Card B costs Y mana...",
      "corrected_math": "Step A: ... Step B: ... Step C: ..."
    }
  ],
  "rejected_loops": [
    {
      "original_cycle": ["Card C", "Card D"],
      "is_valid": false,
      "hallucination_reason": "Card C costs 4 mana. The loop only generates 1 colorless mana. The math does not work."
    }
  ]
}
"""

def fact_check_loops(analysis_output, graph, model="qwen2.5:32b"):
    if not analysis_output.get("validated_cycles") and not analysis_output.get("win_conditions_and_loops"):
        return analysis_output

    proposed_loops = analysis_output.get("validated_cycles", []) + analysis_output.get("win_conditions_and_loops", [])
    cited_data = analysis_output.get("_cited_card_data", {})

    user_prompt = f"""
PROPOSED LOOPS TO VERIFY:
{json.dumps(proposed_loops, indent=2)}

EXACT ORACLE TEXT AND MANA VALUE OF CITED CARDS:
{json.dumps(cited_data, indent=2)}

Verify these loops. Reject any that are physically impossible according to the Oracle text and strict mana math.
"""

    try:
        resp = ollama.chat(
            model=model, format="json", options={"temperature": 0, "num_ctx": 8192},
            messages=[
                {"role": "system", "content": FACT_CHECK_SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt}
            ]
        )
        checked = json.loads(resp["message"]["content"])
    except Exception as e:
        analysis_output["_fact_check_error"] = str(e)
        return analysis_output

    analysis_output["fact_checked_loops"] = checked.get("validated_loops", [])
    analysis_output["rejected_loops"] = checked.get("rejected_loops", [])
    analysis_output["validated_cycles"] = checked.get("validated_loops", [])
    analysis_output["win_conditions_and_loops"] = checked.get("validated_loops", [])
    
    return analysis_output